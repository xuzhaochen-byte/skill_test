#!/usr/bin/env python3
"""Render an ad benchmark report from Aeolus customer metrics and dynamic benchmark rows.

The industry must come from the selected Aeolus advertiser context, and the
benchmark CSV must be generated by aeolus_dynamic_benchmark.py for that same
context.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import shutil
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

METRICS = {
    "ctr": {"label": "CTR", "direction": "higher", "adv_col": "ctr", "bench_prefix": "ctr"},
    "cvr": {"label": "CVR", "direction": "higher", "adv_col": "cvr", "bench_prefix": "cvr"},
    # Cost means spend/consumption scale, not unit cost. Higher spend means a
    # higher benchmark waterline and should not be inverted.
    "cost": {"label": "Spend", "direction": "higher", "adv_col": "total_cost", "bench_prefix": "cost"},
    "play_3s_ratio": {"label": "3s Play Rate", "direction": "higher", "adv_col": "play_3s_ratio", "bench_prefix": "play_3s"},
}
PERCENTILES = [10, 20, 30, 40, 50, 60, 70, 80, 90]


def read_csv(path: Path) -> List[Dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def parse_float(value: Any) -> Optional[float]:
    if value is None:
        return None
    if isinstance(value, (int, float)):
        if isinstance(value, float) and math.isnan(value):
            return None
        return float(value)
    text = str(value).strip()
    if not text:
        return None
    try:
        return float(text.replace(",", ""))
    except ValueError:
        return None


def norm(text: str) -> str:
    return str(text or "").strip().upper()


def find_adv_row(rows: List[Dict[str, str]], adv_id: str, country: str) -> Dict[str, str]:
    matches = [r for r in rows if str(r.get("advertiser_id", "")).strip() == str(adv_id).strip()]
    if not matches:
        raise ValueError(f"adv_id not found in Aeolus metrics CSV advertiser_id column: {adv_id}")
    c_matches = [r for r in matches if norm(r.get("country_code", "")) == norm(country)]
    if not c_matches:
        raise ValueError(f"adv_id={adv_id} has no Aeolus metrics row for country={country}")
    selected = dict(c_matches[0])
    selected["_match_note"] = "exact_adv_id_country"
    selected["_matching_rows"] = str(len(c_matches))
    return selected


def find_dynamic_benchmark_row(rows: List[Dict[str, str]], country: str, industry: str) -> Tuple[Dict[str, str], str]:
    if not industry:
        raise ValueError("--industry is required and must be the selected Aeolus primary-secondary industry")
    exact = [r for r in rows if norm(r.get("country_code", "")) == norm(country) and r.get("industry_category") == industry]
    if not exact:
        raise ValueError(
            "No dynamic benchmark row found for exact country+industry. "
            f"country={country}, industry={industry}. Rerun aeolus_dynamic_benchmark.py for this adv context."
        )
    return exact[0], "exact_dynamic_country_industry"


def metric_benchmark(row: Dict[str, str], prefix: str) -> Dict[str, Optional[float]]:
    return {f"p{p}": parse_float(row.get(f"{prefix}_p{p}")) for p in PERCENTILES}


def estimate_percentile(value: float, points: Dict[str, Optional[float]]) -> float:
    valid = [(p, points.get(f"p{p}")) for p in PERCENTILES if points.get(f"p{p}") is not None]
    valid = [(p, v) for p, v in valid if v is not None]
    if not valid:
        return 0.0
    if value <= valid[0][1]:
        return float(valid[0][0])
    for (p1, v1), (p2, v2) in zip(valid, valid[1:]):
        if value <= v2:
            if v2 == v1:
                return float(p2)
            ratio = (value - v1) / (v2 - v1)
            return p1 + ratio * (p2 - p1)
    return 95.0


def percentile_band(raw_percentile: float) -> str:
    if raw_percentile < 20:
        return "Below P20"
    if raw_percentile < 40:
        return "P20-P40"
    if raw_percentile < 60:
        return "P40-P60"
    if raw_percentile < 80:
        return "P60-P80"
    if raw_percentile < 90:
        return "P80-P90"
    return "Top P90+"


def score_for_metric(raw_percentile: float, direction: str) -> float:
    if direction == "lower":
        return max(0.0, min(100.0, 100.0 - raw_percentile))
    return max(0.0, min(100.0, raw_percentile))


def interpretation(metric: str, raw_percentile: float, score: float, direction: str) -> str:
    label = METRICS[metric]["label"]
    if direction == "lower":
        if score >= 80:
            return f"{label} is very efficient versus benchmark; lower than most peers."
        if score >= 60:
            return f"{label} is better than median benchmark efficiency."
        if score >= 40:
            return f"{label} is around the benchmark middle range."
        if score >= 20:
            return f"{label} is higher than benchmark peers and may pressure efficiency."
        return f"{label} is in the high-cost tail versus benchmark; efficiency risk is high."
    if score >= 90:
        return f"{label} is top-tier versus benchmark."
    if score >= 80:
        return f"{label} is strong and above most peers."
    if score >= 60:
        return f"{label} is above the benchmark middle range."
    if score >= 40:
        return f"{label} is around benchmark median."
    if score >= 20:
        return f"{label} is below median and needs improvement."
    return f"{label} is materially below benchmark."


def format_metric_value(metric: str, value: Optional[float]) -> str:
    if value is None:
        return "N/A"
    if metric in {"ctr", "cvr", "play_3s_ratio"}:
        return f"{value * 100:.2f}%"
    return f"{value:.4g}"


def load_adv_context(path: Path) -> Optional[Dict[str, Any]]:
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    selected = data.get("selected") or {}
    return {
        "source": str(path),
        "selection_rule": data.get("selection_rule"),
        "selected_external_url": selected.get("External Website URL"),
        "selected_country": selected.get("Ad Country Code"),
        "selected_primary_industry": selected.get("Primary Industry"),
        "selected_secondary_industry": selected.get("Secondary Industry"),
        "selected_cvr": selected.get("CVR (Clicks)"),
        "selected_conversions": selected.get("Conversions"),
        "selected_clicks": selected.get("Clicks (Destination)"),
    }


def industry_from_context(path: Optional[str]) -> Optional[str]:
    if not path:
        return None
    p = Path(path)
    if not p.exists():
        return None
    selected = (json.loads(p.read_text(encoding="utf-8")).get("selected") or {})
    primary = str(selected.get("Primary Industry") or "").strip()
    secondary = str(selected.get("Secondary Industry") or "").strip()
    return f"{primary}-{secondary}" if primary and secondary else None


def overall_sentence(score: float) -> str:
    if score >= 80:
        return "Overall performance is strong versus the matched dynamic country and industry benchmark."
    if score >= 60:
        return "Overall performance is above the dynamic benchmark middle range, with room to reach top-quartile levels."
    if score >= 40:
        return "Overall performance is around the dynamic benchmark middle range."
    return "Overall performance is below dynamic benchmark and needs focused optimization."


def recommendations(waterline: Dict[str, Dict[str, Any]]) -> List[str]:
    recs = []
    if waterline.get("play_3s_ratio", {}).get("score", 0) < 60:
        recs.append("Improve the first three seconds with a clearer hook, faster product reveal, and stronger benefit framing.")
    if waterline.get("ctr", {}).get("score", 0) < 60:
        recs.append("Test stronger click drivers: explicit problem-solution openings, visible offer, and more specific outcome claims.")
    if waterline.get("cvr", {}).get("score", 0) < 60:
        recs.append("Check landing-page and ad-message consistency to improve conversion intent after the click.")
    if waterline.get("cost", {}).get("score", 0) < 60:
        recs.append("Spend scale is below the stronger benchmark range; prioritize scalable creatives and audiences once CTR/CVR are stable.")
    if not recs:
        recs.append("Use the current benchmark position as a baseline and test creative variants aimed at P80+ performance.")
    return recs


def build_result(args: argparse.Namespace) -> Dict[str, Any]:
    industry = args.industry or industry_from_context(args.adv_context)
    if not industry:
        raise ValueError("--industry or --adv-context with selected Primary/Secondary Industry is required")

    adv_rows = read_csv(Path(args.adv_data))
    benchmark_rows = read_csv(Path(args.benchmark))
    adv_row = find_adv_row(adv_rows, args.adv_id, args.country)
    bench_row, bench_match = find_dynamic_benchmark_row(benchmark_rows, args.country, industry)

    current_metrics: Dict[str, Optional[float]] = {}
    benchmark_metrics: Dict[str, Dict[str, Optional[float]]] = {}
    waterline: Dict[str, Dict[str, Any]] = {}
    for metric, meta in METRICS.items():
        value = parse_float(adv_row.get(meta["adv_col"]))
        current_metrics[metric] = value
        points = metric_benchmark(bench_row, meta["bench_prefix"])
        benchmark_metrics[metric] = points
        if value is None:
            raw_pct = 0.0
            score = 0.0
            band = "N/A"
            interp = f"{meta['label']} is missing from Aeolus metrics CSV."
        else:
            raw_pct = estimate_percentile(value, points)
            score = score_for_metric(raw_pct, meta["direction"])
            band = percentile_band(raw_pct)
            interp = interpretation(metric, raw_pct, score, meta["direction"])
        waterline[metric] = {
            "label": meta["label"],
            "value": value,
            "formatted_value": format_metric_value(metric, value),
            "raw_percentile": round(raw_pct, 1),
            "score": round(score, 1),
            "band": band,
            "direction": meta["direction"],
            "interpretation": interp,
        }

    scores = [v["score"] for v in waterline.values() if isinstance(v.get("score"), (int, float))]
    overall_score = round(sum(scores) / len(scores), 1) if scores else 0.0
    strengths = [v["interpretation"] for v in waterline.values() if v.get("score", 0) >= 60]
    risks = [v["interpretation"] for v in waterline.values() if v.get("score", 0) < 40]
    if not strengths:
        strengths = ["No metric is clearly above dynamic benchmark yet."]
    if not risks:
        risks = ["No severe dynamic benchmark risk detected from the current metrics."]

    classification = {
        "industry": industry,
        "confidence": 1.0,
        "reason": "Industry is taken from the selected Aeolus advertiser primary/secondary industry.",
        "alternative_industries": [],
        "method": "aeolus_context",
    }

    return {
        "input": {"adv_id": args.adv_id, "url": args.url, "country": args.country},
        "data_sources": {
            "adv_data": str(args.adv_data),
            "benchmark": str(args.benchmark),
            "adv_context": str(args.adv_context) if args.adv_context else None,
        },
        "landing_page": {
            "fetch_status": "not_used_dynamic_benchmark",
            "fetch_error": "",
            "text_excerpt": "",
        },
        "industry_classification": classification,
        "adv_data_match": {
            "advertiser_id": adv_row.get("advertiser_id"),
            "country_code": adv_row.get("country_code"),
            "match_note": adv_row.get("_match_note"),
            "matching_rows": parse_float(adv_row.get("_matching_rows")),
            "raw": {k: v for k, v in adv_row.items() if not k.startswith("_")},
        },
        "current_metrics": current_metrics,
        "benchmark": {
            "country": bench_row.get("country_code"),
            "industry": bench_row.get("industry_category"),
            "support": parse_float(bench_row.get("support")),
            "match_note": bench_match,
            "source": "aeolus_dynamic_benchmark",
            "metrics": benchmark_metrics,
        },
        "waterline": waterline,
        "summary": {
            "overall_score": overall_score,
            "overall": overall_sentence(overall_score),
            "strengths": strengths,
            "risks": risks,
            "recommendations": recommendations(waterline),
        },
        "adv_context": load_adv_context(Path(args.adv_context)) if args.adv_context else None,
    }


def render_outputs(result: Dict[str, Any], output_dir: Path, template_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "benchmark_result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")

    if template_dir.exists():
        for item in template_dir.iterdir():
            target = output_dir / item.name
            if item.is_dir():
                if target.exists():
                    shutil.rmtree(target)
                shutil.copytree(item, target)
            elif item.name != "report-data.template.js":
                shutil.copy2(item, target)

    data_js = "window.BENCHMARK_REPORT_DATA = " + json.dumps(result, ensure_ascii=False, indent=2) + ";\n"
    (output_dir / "report-data.js").write_text(data_js, encoding="utf-8")
    if not (output_dir / "index.html").exists():
        (output_dir / "index.html").write_text(default_html(), encoding="utf-8")


def default_html() -> str:
    return """<!doctype html><meta charset='utf-8'><title>Benchmark Report</title><pre id='out'></pre><script src='report-data.js'></script><script>out.textContent=JSON.stringify(window.BENCHMARK_REPORT_DATA,null,2)</script>"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate an ad benchmark report from dynamic Aeolus benchmark data")
    parser.add_argument("--adv-id", required=True)
    parser.add_argument("--url", required=True)
    parser.add_argument("--country", required=True)
    parser.add_argument("--adv-data", required=True, help="Aeolus metrics CSV from aeolus_adv_metrics.py")
    parser.add_argument("--benchmark", required=True, help="dynamic_benchmark_for_report.csv from aeolus_dynamic_benchmark.py")
    parser.add_argument("--output-dir", default="benchmark_output")
    parser.add_argument("--template-dir", default=None)
    parser.add_argument("--industry", default=None, help="Selected Aeolus Primary-Secondary industry; inferred from --adv-context when omitted")
    parser.add_argument("--adv-context", default=None, help="adv_context.json from aeolus_adv_context.py")
    args = parser.parse_args()

    skill_root = Path(__file__).resolve().parents[1]
    template_dir = Path(args.template_dir) if args.template_dir else skill_root / "assets" / "benchmark-report-template"
    result = build_result(args)
    render_outputs(result, Path(args.output_dir), template_dir)
    print(f"Wrote {Path(args.output_dir) / 'benchmark_result.json'}")
    print(f"Wrote {Path(args.output_dir) / 'index.html'}")
    print(f"Matched dynamic industry: {result['industry_classification']['industry']} ({result['industry_classification']['method']})")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
